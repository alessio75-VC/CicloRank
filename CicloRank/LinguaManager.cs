        private static string _linguaCorrente = InizializzaLingua();

        /// <summary>
        /// Gets the currently active two-letter ISO language code.
        /// </summary>
        public static string LinguaCorrente => _linguaCorrente;

        /// <summary>
        /// Occurs when the active application language changes.
        /// </summary>
        public static event Action? LinguaCambiata;

        /// <summary>
        /// Loads the saved language preference from disk or falls back to the operating system's
        /// current UI language (defaulting to English if unsupported).
        /// </summary>
        private static string InizializzaLingua()
        {
            try
            {
                if (!File.Exists(FilePreferenzaLingua) && File.Exists("lingua.cfg"))
                {
                    File.Copy("lingua.cfg", FilePreferenzaLingua, true);
                }
                if (File.Exists(FilePreferenzaLingua))
                {
                    string salvata = File.ReadAllText(FilePreferenzaLingua, Utf8NoBom).Trim().ToLowerInvariant();
                    if (Dizionari.ContainsKey(salvata))
                    {
                        return salvata;
                    }
                }
            }
            catch { }

            string isoSistema = CultureInfo.CurrentUICulture.TwoLetterISOLanguageName.ToLowerInvariant();
            return Dizionari.ContainsKey(isoSistema) ? isoSistema : "en";
        }

        /// <summary>
        /// Switches the active UI language, saves the preference to disk, and raises <see cref="LinguaCambiata"/>.
        /// </summary>
        /// <param name="codiceLingua">Two-letter ISO code of the target language.</param>
        public static void ImpostaLingua(string codiceLingua)
        {
            if (string.IsNullOrWhiteSpace(codiceLingua)) return;

            string norm = codiceLingua.Trim().ToLowerInvariant();
            if (!Dizionari.ContainsKey(norm) || norm == _linguaCorrente) return;

            _linguaCorrente = norm;

            try
            {
                File.WriteAllText(FilePreferenzaLingua, _linguaCorrente, Utf8NoBom);
            }
            catch { }

            LinguaCambiata?.Invoke();
        }

        /// <summary>
        /// Translates a localization key into the active language, falling back to English
        /// or the raw key if no translation entry exists.
        /// </summary>
        /// <param name="chiave">Localization dictionary key.</param>
        /// <returns>The localized string.</returns>
        public static string T(string chiave)
        {
            if (Dizionari.TryGetValue(_linguaCorrente, out var dict) && dict.TryGetValue(chiave, out var valore))
            {
                return valore;
            }

            if (Dizionari["en"].TryGetValue(chiave, out var fallbackEn))
            {
                return fallbackEn;
            }

            return chiave;
        }

        /// <summary>
        /// Formats a lap column header (e.g., "giro 1", "Lap 1", "ç¬¬1åœˆ") according to the active language.
        /// </summary>
        /// <param name="numeroGiro">1-based lap number.</param>
        /// <returns>Localized lap column header text.</returns>
        public static string FormatGiroHeader(int numeroGiro)
        {
            return _linguaCorrente switch
            {
                "it" => $"giro {numeroGiro}",
                "zh" => $"第{numeroGiro}圈",
                "ja" => $"{numeroGiro}周目",
                _ => $"{T("RptColLap")} {numeroGiro}"
            };
        }

        /// <summary>
        /// Converts a sport name string into Title Case (capitalizing the first letter of each word).
        /// </summary>
        public static string FormattaNomeSport(string? testo)
        {
            if (string.IsNullOrWhiteSpace(testo)) return string.Empty;
            string trimmed = testo.Trim();
            var words = trimmed.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries);
            for (int i = 0; i < words.Length; i++)
            {
                if (words[i].Length == 1)
                    words[i] = words[i].ToUpperInvariant();
                else
                    words[i] = char.ToUpper(words[i][0]) + words[i].Substring(1);
            }
            return string.Join(" ", words);
        }

        /// <summary>
        /// Builds the dynamic report header title by combining the localized "Classification" prefix
        /// with the formatted sport name (e.g., "Classifica Ciclismo" or "Classification Cycling").
        /// </summary>
        public static string CostruisciTitoloClassificaSport(string? sportOverride = null)
        {
            string prefisso = T("RptClassificationPrefix");
            if (string.IsNullOrWhiteSpace(prefisso) || prefisso == "RptClassificationPrefix")
            {
                prefisso = T("RptDocTitle");
            }

            string sportRaw = !string.IsNullOrWhiteSpace(sportOverride)
                ? sportOverride
                : MainForm.SportCorrente;

            string sportFormattato = FormattaNomeSport(sportRaw);
            return string.IsNullOrWhiteSpace(sportFormattato)
                ? prefisso
                : $"{prefisso} {sportFormattato}";
        }
