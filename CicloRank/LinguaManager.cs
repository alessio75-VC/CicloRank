    /// <summary>
    /// Represents a selectable UI language option pairing an ISO 639-1 language code
    /// with its localized native display name.
    /// </summary>
    public sealed class OpzioneLingua
    {
        /// <summary>Gets the two-letter ISO language code (e.g., "it", "en", "es").</summary>
        public string Codice { get; }
        /// <summary>Gets the native display name shown in the language selector dropdown.</summary>
        public string NomeVisualizzato { get; }

        /// <summary>
        /// Initializes a new <see cref="OpzioneLingua"/> option.
        /// </summary>
        public OpzioneLingua(string codice, string nomeVisualizzato)
        {
            Codice = codice;
            NomeVisualizzato = nomeVisualizzato;
        }

        /// <summary>Returns the native display name for ComboBox rendering.</summary>
        public override string ToString() => NomeVisualizzato;
    }

